import fs from 'node:fs';
import path from 'node:path';
import { publishedEntries, readEntries } from '../lib/content';
// Next static export requires at least one generated param per dynamic route.
// With no published posts, omit the route entirely; keep its renderer in source.
readEntries('projects');
readEntries('posts');
const routeFile = path.join(process.cwd(), 'app', '[locale]', 'blog', '[slug]', 'page.tsx');
if (publishedEntries('posts').length) {
  fs.mkdirSync(path.dirname(routeFile), { recursive: true });
  fs.writeFileSync(routeFile, "// Generated by scripts/prepare-routes.ts. Do not edit.\nexport { default, generateMetadata, generateStaticParams } from '@/lib/routes/blog-post';\nexport const dynamicParams = false;\n");
  console.log('Blog article route enabled for published posts.');
} else {
  fs.rmSync(routeFile, { force: true });
  console.log('No published posts: blog article routes omitted from export.');
}
